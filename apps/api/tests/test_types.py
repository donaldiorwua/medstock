import uuid
from datetime import datetime, timedelta, timezone

import pytest
from sqlalchemy import insert, select, text
from sqlalchemy.exc import IntegrityError, StatementError

from app.core.db import Database
from app.models.base import NAMING_CONVENTION
from tests.probe import ProbeStatus, Widget, probe_child, probe_parent


def test_naming_convention_covers_every_constraint_kind() -> None:
    assert set(NAMING_CONVENTION) == {"ix", "uq", "ck", "fk", "pk"}


def test_uuid_utc_datetime_json_and_enum_round_trip(database: Database, probe_tables: None) -> None:
    parent_id = uuid.uuid4()
    local_time = datetime(2026, 1, 2, 15, 30, tzinfo=timezone(timedelta(hours=1)))
    with database.unit_of_work(write=True) as session:
        session.execute(
            insert(probe_parent).values(
                id=parent_id,
                created_at=local_time,
                payload={"items": [1, 2], "ok": True},
                status=ProbeStatus.ACTIVE,
            )
        )
    with database.unit_of_work() as session:
        row = session.execute(select(probe_parent).where(probe_parent.c.id == parent_id)).one()

    assert row.id == parent_id
    assert row.created_at == local_time  # same instant
    assert row.created_at.utcoffset() == timedelta(0)  # returned as UTC
    assert row.payload == {"items": [1, 2], "ok": True}
    assert row.status is ProbeStatus.ACTIVE


def test_naive_datetimes_are_rejected(database: Database, probe_tables: None) -> None:
    with pytest.raises((StatementError, ValueError)), database.unit_of_work(write=True) as session:
        session.execute(
            insert(probe_parent).values(
                id=uuid.uuid4(),
                created_at=datetime(2026, 1, 1, 12, 0),  # no tzinfo
                status=ProbeStatus.ACTIVE,
            )
        )


def test_database_check_constraint_rejects_unknown_enum_values(
    database: Database, probe_tables: None
) -> None:
    sql = (
        "INSERT INTO probe_parent (id, created_at, status) "
        "VALUES ('{id}', '2026-01-01 00:00:00', '{status}')"
    )
    # Sanity: a valid value goes through the raw path, so the failure below is the CHECK.
    with database.unit_of_work(write=True) as session:
        session.execute(text(sql.format(id=uuid.uuid4().hex, status="active")))
    with pytest.raises(IntegrityError), database.unit_of_work(write=True) as session:
        session.execute(text(sql.format(id=uuid.uuid4().hex, status="bogus")))


