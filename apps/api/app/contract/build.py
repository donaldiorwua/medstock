"""Generate, export and check the contract artifacts in docs/contract/.

    openapi.json   the full OpenAPI description, generated by FastAPI from the code
    enums.json     every enum in app/core/enums.py with its values
    errors.json    the error catalogue, with an example body per code

All three are produced deterministically (sorted keys, 2-space indent, LF, trailing newline).
"""

import difflib
import json
from pathlib import Path
from typing import Any

from fastapi import FastAPI
from pydantic_settings import SettingsConfigDict

from app.contract import CONTRACT_VERSION
from app.core.config import Settings
from app.core.enums import ALL_ENUMS
from app.core.error_catalogue import CATALOGUE, EXAMPLE_REQUEST_ID, ErrorCode
from app.main import create_app

# apps/api/app/contract/build.py -> repository root is four levels up from this file's folder.
CONTRACT_DIR = Path(__file__).resolve().parents[4] / "docs" / "contract"
CONTRACT_FILES = ("openapi.json", "enums.json", "errors.json")
EXAMPLES_DIR = CONTRACT_DIR / "examples"
_HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")


class _ContractSettings(Settings):
    """Settings used only to build the app for export: never reads a .env file."""

    model_config = SettingsConfigDict(env_file=None)


def build_app() -> FastAPI:
    return create_app(_ContractSettings(app_env="test", database_url="sqlite:///:memory:"))


def enums_document() -> dict[str, Any]:
    enums = {
        enum_cls.__name__: {
            "description": (enum_cls.__doc__ or "").strip(),
            "values": [member.value for member in enum_cls],
        }
        for enum_cls in sorted(ALL_ENUMS, key=lambda e: e.__name__)
    }
    return {"contract_version": CONTRACT_VERSION, "enums": enums}


def errors_document() -> dict[str, Any]:
    errors: dict[str, Any] = {}
    for code in sorted(ErrorCode, key=lambda c: c.value):
        spec = CATALOGUE[code]
        errors[code.value] = {
            "http_status": spec.http_status,
            "meaning": spec.meaning,
            "example": {
                "error": {
                    "code": code.value,
                    "message": spec.example_message,
                    "details": spec.example_details,
                    "request_id": EXAMPLE_REQUEST_ID,
                }
            },
        }
    return {"contract_version": CONTRACT_VERSION, "errors": errors}


def _dump(document: dict[str, Any]) -> str:
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def load_examples(examples_dir: Path = EXAMPLES_DIR) -> dict[str, dict[int, dict[str, Any]]]:
    """Read examples/<operationId>/<status>.json into {operationId: {status: file}}."""
    examples: dict[str, dict[int, dict[str, Any]]] = {}
    if not examples_dir.is_dir():
        return examples
    for path in sorted(examples_dir.glob("*/*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        examples.setdefault(path.parent.name, {})[int(data["response"]["status"])] = data
    return examples


def embed_examples(spec: dict[str, Any], examples: dict[str, dict[int, dict[str, Any]]]) -> None:
    """Copy each example into openapi.json so a mock server can run from that one file.

    Response bodies go on the matching status. The request body of the 2xx example goes on
    the operation's requestBody. Examples for undeclared statuses are skipped here; a test
    reports them.
    """
    for path_item in spec.get("paths", {}).values():
        for method in _HTTP_METHODS:
            operation = path_item.get(method)
            if not operation:
                continue
            for status, example in sorted(examples.get(operation["operationId"], {}).items()):
                response = operation.get("responses", {}).get(str(status))
                if response is None:
                    continue
                content_type = example["response"].get("content_type", "application/json")
                media = response.setdefault("content", {}).setdefault(content_type, {})
                media["example"] = example["response"]["body"]
                request_body = operation.get("requestBody")
                body = example.get("request", {}).get("body")
                if 200 <= status < 300 and request_body is not None and body is not None:
                    request_body["content"]["application/json"]["example"] = body


def generate(examples_dir: Path = EXAMPLES_DIR) -> dict[str, str]:
    """Return {file name: exact file content} for every contract artifact."""
    app = build_app()
    try:
        openapi = app.openapi()
    finally:
        app.state.db.dispose()
    embed_examples(openapi, load_examples(examples_dir))
    return {
        "openapi.json": _dump(openapi),
        "enums.json": _dump(enums_document()),
        "errors.json": _dump(errors_document()),
    }


def export(directory: Path = CONTRACT_DIR) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name, content in generate().items():
        path = directory / name
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def check(directory: Path = CONTRACT_DIR) -> list[str]:
    """Compare the committed files with what the code generates now.

    Returns one human-readable problem per file that is missing or different.
    An empty list means the contract is in sync.
    """
    problems: list[str] = []
    for name, expected in generate().items():
        path = directory / name
        if not path.exists():
            problems.append(f"{name}: file is missing.")
            continue
        actual = path.read_text(encoding="utf-8")  # universal newlines: CRLF checkouts are fine
        if actual != expected:
            diff = "".join(
                difflib.unified_diff(
                    actual.splitlines(keepends=True),
                    expected.splitlines(keepends=True),
                    fromfile=f"committed/{name}",
                    tofile=f"generated/{name}",
                    n=2,
                )
            )
            problems.append(f"{name}: differs from the code.\n{diff}")
    return problems
